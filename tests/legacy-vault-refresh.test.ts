// 9. THE SAME CRITERION, DRIVEN THROUGH THE REAL WIZARD PATH.
//
// Sections 1-8 call `generateNotes` directly, which is precise but leaves one
// question open: does the flow that a user actually drives hand the engine the
// destination and the ownership answer the review screen showed them? Here the
// pre-fix vault is built by RUNNING THE WIZARD, so the refresh cannot differ
// from the original import in any way except the one under test, and the
// refresh is `flow.generate()` -- config, recipe, destination, ownership and
// overwrite mode all resolved by the flow itself.
//
// It also reaches the two clauses nothing else can: what the user is SHOWN when
// the refresh finishes, and that the refresh survives the wizard's own choice of
// destination and ownership rather than a hand-passed one.
//
// A-8 RESTATED (2026-08-30) asks for this end to end in BOTH overwrite modes,
// not just `replace`. Under `skip` the second run creates nothing at all, which
// is precisely the run that used to orphan every hub, so it is the mode where an
// end-to-end check has the most to say.
// ===========================================================================

describe.each(['replace', 'skip'] as const)('two real wizard runs, the second a refresh (overwriteMode %s)', (overwriteMode) => {
	/**
	 * Run the wizard once into the bare shared root -- which is exactly how the
	 * pre-fix vaults arose, the destination field having been seeded with the
	 * global output path -- then rewrite the result into the pre-fix on-disk
	 * shape and hand the vault to a second, untouched flow.
	 */
	async function firstImportThenRefresh() {
		const vault = makeVault();

		const first = makeFlow(vault.app);
		(first.flow as unknown as { destinationEdited: boolean }).destinationEdited = true;
		first.flow.outputPath = SHARED_ROOT;
		first.flow.overwriteMode = 'replace';
		first.flow.currentStep = 4;
		await inner(first.flow).prepareStep3(true);
		await first.flow.generate();

		deMigrateToPreFix(vault.files, SHARED_ROOT);
		vault.files.set(
			`${SHARED_ROOT}/Persistence.md`,
			`${vault.files.get(`${SHARED_ROOT}/Persistence.md`)!}\n${HUB_PROSE}\n`,
		);
		const before = new Map(vault.files);
		forgetSeedWrites(vault);

		const second = makeFlow(vault.app);
		second.flow.overwriteMode = overwriteMode;
		await inner(second.flow).prepareStep3(true);
		// A-8 restated: "refreshed BY EXPLICIT CHOICE". What the flow answers before
		// the click is kept, because "the default was never a refresh" is half of
		// what this scenario has to prove.
		const unchosen = inner(second.flow).currentOutputPath();
		pressTheOffer(second.flow);
		second.flow.currentStep = 4;
		const destination = inner(second.flow).currentOutputPath();
		// Only the refresh's notices, so the first import's cannot be mistaken for
		// the report the user reads at the end of the run under test.
		notices.length = 0;
		await second.flow.generate();

		return { vault, before, destination, unchosen, second };
	}

	it('leaves the first import flat, with its concept notes AND its hubs at the bare root', async () => {
		// The starting state the whole criterion is about. Asserted rather than
		// assumed: a fixture that quietly nested itself would test nothing.
		const { before } = await firstImportThenRefresh();
		expect([...before.keys()].sort()).toEqual([
			'Ontologies/Discovery.md',
			'Ontologies/Ontologies.md',
			'Ontologies/Persistence.md',
			'Ontologies/T1078.md',
			'Ontologies/T1078/T1078.001.md',
			'Ontologies/T1098.md',
			'Ontologies/T1590.md',
			'Ontologies/T1595.md',
			'Ontologies/T1595/T1595.002.md',
		]);
	});

	it('refreshes into that same bare root, once the user asks for a refresh', async () => {
		const { destination, unchosen } = await firstImportThenRefresh();
		// AM-5, end to end: with no click this run was a new set headed for a
		// folder of its own. The click is what put it back on the set's own root.
		expect(unchosen).toBe(DERIVED_ROOT);
		expect(destination).toBe(SHARED_ROOT);
		expect(destination).not.toBe(DERIVED_ROOT);
	});

	it('leaves the vault holding exactly the notes it held before', async () => {
		const { vault, before } = await firstImportThenRefresh();
		expect([...vault.files.keys()].sort()).toEqual([...before.keys()].sort());
		expect(duplicateCuries(vault.files)).toEqual([]);
		expect(vault.rename).not.toHaveBeenCalled();
	});

	it('keeps the prose the user typed onto a hub', async () => {
		const { vault } = await firstImportThenRefresh();
		expect(vault.files.get(`${SHARED_ROOT}/Persistence.md`)).toContain(HUB_PROSE);
	});

	it('raises no ambiguous-identity error, in the only place the user would see one', async () => {
		// End to end there is no `GenerationResult` to inspect: what the run
		// concluded reaches the user as a notice, or not at all. AM-4 makes an error
		// draw the results screen, so a clean close IS the assertion that none was
		// raised -- and the notice is checked too, because "closed quietly" was
		// exactly the old failure.
		const { second } = await firstImportThenRefresh();
		expect(noticeText()).not.toMatch(/Ambiguous identity|finished with \d+ errors/);
		expect(second.texts.filter((t) => /Ambiguous identity/.test(t))).toEqual([]);
	});

	// AM-3. This was `it.failing('tells the user that nothing moved')`: the results
	// screen draws only when something moved, orphaned or (now) errored, so on the
	// A-8 scenario itself -- a refresh that correctly moves nothing -- the user was
	// told nothing at all and could not tell "nothing moved" from "nobody checked".
	// The counts moved onto the success notice, which fires on every run, including
	// the one that closes.
	it('tells the user that nothing moved and nothing was orphaned', async () => {
		const { second } = await firstImportThenRefresh();
		expect(noticeText()).toContain('Nothing moved. No orphans.');
		// Still closes: AM-3 deliberately did NOT force a screen onto a clean run.
		expect(second.close).toHaveBeenCalledTimes(1);
		expect(second.texts.filter((t) => /Moved|Orphans/.test(t))).toEqual([]);
	});

	it('reports the run it actually did, rather than a fixed sentence', async () => {
		// The counts must be read off the result, not printed unconditionally. The
		// two modes take different branches through the write loop -- `replace`
		// rewrites all six notes, `skip` keeps all six -- and the notice has to
		// describe the one that happened.
		const { second } = await firstImportThenRefresh();
		void second;
		expect(noticeText()).toMatch(
			overwriteMode === 'replace'
				? /✅ Created 6 notes in [\d.]+s\. Nothing moved\. No orphans\./
				: /✅ Created 0 notes, skipped 6 existing in [\d.]+s\. Nothing moved\. No orphans\./,
		);
	});

	// AM-7, end to end. "No orphans" and "orphans not checked" are different
	// sentences, and the clean refresh has to earn the first one: a build that
	// suppressed detection here would still look clean to every other assertion
	// in this section, because a suppressed count is an ABSENT count.
	it('says the orphan question was answered, not that it was skipped', async () => {
		const { second } = await firstImportThenRefresh();
		void second;
		expect(noticeText()).not.toContain('Orphans not checked.');
		expect(noticeText()).toContain('No orphans.');
	});

	// A-8 restated, the clause about the user's own vault: every path the run
	// reports back exists, and no two files claim one identity. Asserted here as
	// well as on the engine result in section 2, because end to end is where a
	// path the wizard invented rather than wrote would show up.
	it('reports a vault that matches what it says about it', async () => {
		const { vault } = await firstImportThenRefresh();
		expect(duplicateCuries(vault.files)).toEqual([]);
		const hubs = [...vault.files.values()].filter((text) => frontmatterOf(text).kind === 'hub');
		expect(hubs.length).toBeGreaterThan(0);
		// Every wikilink target a hub lists resolves to a note that is really there.
		for (const [path, text] of vault.files) {
			for (const [, target] of text.matchAll(/\[\[([^\]|#]+)/g)) {
				const basename = target.trim();
				const found = [...vault.files.keys()].some((p) => p.endsWith(`/${basename}.md`) || p === `${basename}.md`);
				expect(found ? true : `${path} -> ${basename}`).toBe(true);
			}
		}
	});
});

