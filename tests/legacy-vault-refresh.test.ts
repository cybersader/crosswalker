/**
 * legacy-vault-refresh.test.ts -- the D1 Part A acceptance criterion (A-8).
 *
 * THE SCENARIO THIS FILE EXISTS FOR
 *
 * A user imported a source before the per-import root rule ran. Their notes and
 * their hubs sit in the shared output folder ("Ontologies") itself, and their
 * provenance records `{id, scheme}` and no destination, because nothing recorded
 * one yet. They now refresh that import with a build where the per-import root
 * rule DOES run, and the derived default names a folder their notes have never
 * been in ("Ontologies/attack-mini").
 *
 * Nothing in that chain moves the existing import. It writes a SECOND copy of it
 * beside the first, reports paths the user has never seen, strands hubs at the
 * old address under identities nothing will claim again, and -- once two files
 * claim one curie -- raises "Ambiguous identity", which suppresses orphan
 * reporting for the entire run and surfaces as "N rows failed" for something
 * that is not a row.
 *
 * PART A'S ANSWER, AND WHY THE TESTS ARE SHAPED THIS WAY
 *
 * A refresh never changes a set's root. The destination for a refresh IS the
 * set's existing root, resolved once from the notes the set already owns. So the
 * destination is never hard-coded into the refresh below: it is read back out of
 * a real `ImportFlow` through the same accessor every write path uses, because
 * "where does this refresh land" is the decision the whole failure hangs on.
 *
 * WHO DECIDES THAT IT IS A REFRESH AT ALL (AM-5)
 *
 * Ownership used to be inferred: first from the folder, then from the stamped
 * recipe id and ontology prefix. Four passes narrowed that guess and four passes
 * were defeated by it, because none of those facts names an owner. AM-5 removed
 * it. The default is ALWAYS a new set, matching is demoted to an offer, and a
 * click is the only route into a refresh -- so every scenario below that is
 * about a refresh presses that offer (`askWhereARefreshLands` / `pressTheOffer`)
 * or picks the set out of the list (`chooseFromTheList`), and the answer BEFORE
 * the click is asserted too, because "the default was never a refresh" is half
 * of what these tests exist to show.
 *
 * WHY THE PRE-FIX VAULT IS BUILT BY DE-MIGRATION
 *
 * The seed is generated by the current engine and then rewritten INTO the older
 * on-disk shape (destination stamp removed, hub curies returned to their
 * address-derived form). That is more faithful than hand-writing notes: every
 * byte except the two deliberate differences is exactly what a real vault holds,
 * so the test cannot pass by seeding something the engine would never produce.
 *
 * WHAT IS ASSERTED, AND WHERE
 *
 *   1. Where a refresh lands, and which set it is attributed to (A-1 to A-3).
 *   2. The acceptance clauses themselves, under BOTH overwrite modes (A-8).
 *   3. A second, unrelated framework in the same legacy vault (A-8 companion).
 *   4. A cold metadata cache at step 3 (A-8 companion, A-4).
 *   5. Segment-wise root recovery and failing closed, at the wizard (A-3).
 *   6. The new-set occupancy guard and suppressed moves under skip (A-6).
 *   7. What the results screen renders (A-7).
 *   8. The isolating experiment that showed the skip-mode gap was not the
 *      destination rule's doing, now the control that it stays closed (AM-2).
 *   9. The same criterion driven end to end through two real wizard runs, in
 *      BOTH overwrite modes (A-8 restated).
 *  10. The classic import path, which stamps no ontology of its own (AM-1).
 *  11. What the success notice says on every run (AM-3).
 *  12. An identity collision on a run that would otherwise close (AM-4).
 *  13. Nothing preselects a refresh; the offer is a suggestion; every set is
 *      listed; and the three sources that defeated pass-4 matching (AM-5).
 *  14. A legacy set whose ontology is the placeholder: pinned to what its own
 *      notes carry, on the first refresh, and reused after (AM-6).
 *  15. A run that could not check for orphans says so, and never prints a zero
 *      (AM-7). AM-8 -- the same rule at the SSSOM entry point -- lives in
 *      tests/sssom-import-modal-errors.test.ts, because it is a different modal.
 *  16. The engine never adopts: an explicit id refreshes, anything else mints
 *      (AM-9), asserted at the engine boundary because that is the only place
 *      "nothing below the click can choose a set" can be true.
 *  17. "Not yet discovered" is not "none" (AM-10).
 *  18. The pass-4 escape routes replayed at the engine, with no wizard at all.
 *  19. A write never crosses a set boundary: the owned index RESOLVES, the
 *      vault-wide index only DETECTS, and a foreign claim is reported by name
 *      and refused -- concepts, hubs, and notes that carry no owner at all
 *      (AM-12), in both overwrite modes.
 *  20. A new set whose curie space is already occupied mints set-qualified, so
 *      two releases of one framework coexist by construction (AM-13).
 *  21. A-8's final sentence end to end: the escape routes at the NOTE level,
 *      through a real wizard, in both overwrite modes.
 *
 * THE THREE GAPS THIS FILE USED TO PIN WITH `it.failing`, AND WHERE THEY WENT
 *
 *   a. `skip` mode orphaned every hub and restamped none (section 2, isolated
 *      in section 8). Closed by AM-2: a row this run KEPT is still a row it
 *      vouches for, so the hubs those rows imply are marked produced without
 *      anything being rewritten. Both clauses are ordinary `it` again, and
 *      section 8 now asserts the absence rather than the presence.
 *   b. "and the orphan count" was invisible on a clean run, because the screen
 *      renders the orphan line only when the count is non-zero (section 7).
 *      Closed by AM-3, but NOT on the screen: a clean refresh never draws one.
 *      The counts ride on the success notice instead, on every run (section 11).
 *   c. A clean refresh closed the host instead of reporting anything (section
 *      9). Closed by AM-3 the same way: it still closes, and the user is still
 *      told both numbers, because the notice fires before the close.
 *
 * A regression in any of the three turns this suite red at the named section.
 *
 * TESTS RETIRED BY AM-5, AND WHAT REPLACED THEM
 *
 *   - 'preselects refreshing exactly the set whose stamps this source carries'
 *     (section 1) asserted the pass-4 default. Replaced by 'preselects nothing
 *     at all, even when exactly one set matches this source', on the same input.
 *   - 'still refreshes its OWN set when the same source comes back' (section 10)
 *     asserted the same default on the classic path. Replaced by 'offers its OWN
 *     set when the same source comes back, and refreshes only on the click'.
 *
 * THE FOURTH GAP, RETIRED BY AM-12 AND AM-13
 *
 *   Section 13's 'leaves the first crosswalk holding its own root hub' was
 *   `it.failing` through pass 6. A recipe mints one root-hub curie per ontology
 *   (`<ontology>:hub/_root`) with nothing set-qualifying it, and the identity
 *   index `resolveWriteTarget` consulted was whole-vault rather than scoped to
 *   the writing set -- so a second import under a SHARED ontology label landed
 *   as its own new set and still renamed the first set's root hub into its own
 *   folder and re-stamped it. It is an ordinary `it` now, and the two halves of
 *   the close are tested apart in sections 19 and 20: AM-13 stops the identity
 *   spaces overlapping, AM-12 refuses the write if they ever do.
 *
 *   NOTHING IN THIS FILE IS PINNED WITH `it.failing` ANY MORE.
 *
 * TESTS RETIRED BY AM-12, AND WHY
 *
 *   Section 6's `skipIntoAMovedRoot` used to hand the engine no ownership
 *   option at all, which under AM-9 mints a new set and under AM-12 refuses
 *   every seeded row -- so no move was even proposed and "the move was
 *   suppressed" became unfalsifiable. It now names the seeded set explicitly,
 *   because a move is only reachable INSIDE the set that owns the notes, which
 *   is the only place a move was ever legitimate.
 *
 *   Section 13's `twoXwalkCrosswalks` used to hard-code `importSet: 'new'` for
 *   the second import, discarding the ownership answer the flow above it was
 *   built to produce. It threads that answer now, which is what lets AM-13
 *   qualify the mint.
 */

